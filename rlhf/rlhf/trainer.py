"""
WhisperRLHFTrainer -- fine-tune Whisper Medium via DPO.

 DPO (Direct Preference Optimisation, Rafailov et al. 2023)
  ----------------------------------------------------------
  Adapted for Whisper encoder-decoder using teacher-forced log probs:
    log_pi(y|x) = -NLL_sum(y|x)         # per-sequence sum, not mean
  Loss:
    L = -log sigma(beta *[(log pi_theta(y_w|x) - log pi_ref(y_w|x))
                   -(log pi_theta(y_l|x) - log pi_ref(y_l|x))])

    Preference pairs (y_w, y_l) combine durable human A/B choices with one
    round-scoped synthetic JSONL artifact generated by the active policy and the
    current AudioTextRewardModel.
  See docs/DPO_PRIMER.md.
"""

from __future__ import annotations

import json
import logging
import math
from pathlib import Path
from typing import Optional, Union

import torch
import torch.nn.functional as F
from torch.utils.data import DataLoader
from tqdm import tqdm

from .config import RLHFConfig
from .dataset import WhisperRLHFCollator, WhisperRLHFDataset
from .reference_model import ReferenceWhisper
from .preference_data import build_dpo_rows
from utils.torch_runtime import configure_torch_runtime, use_fused_optimizer
from utils.training_control import EarlyStopping

log = logging.getLogger(__name__)

_MAX_INITIAL_REFERENCE_OFFSET = 0.1


def _initial_reference_offset(
    pi_ch: torch.Tensor,
    pi_re: torch.Tensor,
    ref_ch: torch.Tensor,
    ref_re: torch.Tensor,
) -> float:
    offset = (pi_ch - ref_ch) - (pi_re - ref_re)
    return float(offset.detach().abs().mean().cpu())


def _scaled_optimizer_step(
    model: torch.nn.Module,
    optimizer: torch.optim.Optimizer,
    scaler: torch.cuda.amp.GradScaler,
    max_grad_norm: float,
) -> Optional[float]:
    scaler.unscale_(optimizer)
    gradient_norm = torch.nn.utils.clip_grad_norm_(
        model.parameters(), max_grad_norm, error_if_nonfinite=not scaler.is_enabled()
    )
    scale_before = scaler.get_scale()
    scaler.step(optimizer)
    scaler.update()
    optimizer.zero_grad()
    if scaler.get_scale() < scale_before:
        log.warning(
            "DPO optimizer update skipped due to non-finite gradients; "
            "AMP scale reduced from %g to %g",
            scale_before, scaler.get_scale(),
        )
        return None
    norm = float(gradient_norm.detach().cpu())
    if not math.isfinite(norm):
        raise RuntimeError("DPO optimizer update has a non-finite gradient norm")
    return norm


class WhisperRLHFTrainer:
    """
    Fine-tunes Whisper policy via DPO.
    Dataset: reward_scores joined with hypothesis pairs (populated by run_score_rewards.py).
    """

    def __init__(
        self,
        config: RLHFConfig,
        store,  # FeedbackStore
        paths,  # PathsConfig
    ) -> None:
        self.config = config
        self.store = store
        self.paths = paths
        self.n_human_pairs = 0
        self.n_synthetic_pairs = 0

    # -- Main entry point -------------------------------------------------------

    def train(
        self,
        output_dir: Union[str, Path],
        synthetic_data: Optional[str] = None,
    ) -> Path:
        """
        Run DPO fine-tuning. Returns the saved LoRA checkpoint directory.

        Raises:
            ValueError: if insufficient reward scores in DB.
        """
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

        rows, self.n_human_pairs, self.n_synthetic_pairs = build_dpo_rows(
            self.store,
            synthetic_data,
            self.config.max_synthetic_to_human_ratio,
            self.config.synthetic_seed,
            (
                f"{self.config.whisper_model_id}+lora:"
                f"{Path(self.config.resume_from_checkpoint).name}"
                if self.config.resume_from_checkpoint
                else self.config.whisper_model_id
            ),
        )
        n = len(rows)
        if n < self.config.min_reward_scores:
            raise ValueError(
                f"Only {n} DPO pairs available (need >= {self.config.min_reward_scores}; "
                f"human={self.n_human_pairs}, synthetic={self.n_synthetic_pairs})."
            )

        return self._train_dpo(rows, output_dir)

    # -- Model loading helpers --------------------------------------------------

    def _load_policy(self):
        """Load Whisper + LoRA adapter. Returns (model, processor)."""
        from utils.policy_checkpoint import validate_policy_checkpoint

        if self.config.resume_from_checkpoint:
            validate_policy_checkpoint(
                Path(self.config.resume_from_checkpoint), self.config.whisper_model_id
            )
        configure_torch_runtime()
        import torch
        from peft import LoraConfig, TaskType, get_peft_model
        from transformers import WhisperForConditionalGeneration, WhisperProcessor

        log.info("Loading Whisper policy: %s", self.config.whisper_model_id)
        dtype = (
            torch.float16 if self.config.torch_dtype == "float16" else torch.bfloat16
        )

        processor = WhisperProcessor.from_pretrained(self.config.whisper_model_id)
        # Lock language/task prefix tokens -- without this, the DPO collator
        # (WhisperRLHFCollator._tokenise_labels) tokenises chosen/rejected labels
        # without the <|pl|><|transcribe|> prefix, which un-teaches the model to
        # commit to Polish over successive DPO rounds (see CONTRACT.md §12).
        processor.tokenizer.set_prefix_tokens(
            language=self.config.language, task=self.config.task
        )
        forced_ids = processor.get_decoder_prompt_ids(
            language=self.config.language, task=self.config.task
        )

        resume = self.config.resume_from_checkpoint
        if resume and not Path(resume).exists():
            raise ValueError(f"Policy checkpoint does not exist: {resume}")
        if resume:
            from peft import PeftModel

            base = WhisperForConditionalGeneration.from_pretrained(
                self.config.whisper_model_id,
                torch_dtype=dtype,
                attn_implementation=self.config.attn_implementation,
            ).to(self.config.device)
            base.config.forced_decoder_ids = forced_ids
            model = PeftModel.from_pretrained(base, resume, is_trainable=True)
            log.info("Resumed from LoRA checkpoint: %s", resume)
        else:
            base = WhisperForConditionalGeneration.from_pretrained(
                self.config.whisper_model_id,
                torch_dtype=dtype,
                attn_implementation=self.config.attn_implementation,
            ).to(self.config.device)
            base.config.forced_decoder_ids = forced_ids
            lora_cfg = LoraConfig(
                r=self.config.lora_r,
                lora_alpha=self.config.lora_alpha,
                lora_dropout=self.config.lora_dropout,
                target_modules=self.config.lora_target_modules,
                task_type=TaskType.SEQ_2_SEQ_LM,
                bias="none",
            )
            model = get_peft_model(base, lora_cfg)
            model.print_trainable_parameters()

        # DPO compares policy and reference likelihoods. Keep dropout disabled
        # for both models; eval mode does not disable gradients.
        model.eval()
        return model, processor

    def _build_ref_model(self) -> ReferenceWhisper:
        return ReferenceWhisper(
            model_id=self.config.whisper_model_id,
            adapter_checkpoint=(
                self.config.reference_checkpoint or self.config.resume_from_checkpoint
            ),
            load_in_4bit=self.config.reference_in_4bit,
            device=self.config.device,
            torch_dtype=self.config.torch_dtype,
            attn_implementation=self.config.attn_implementation,
        )

    # -- DPO training -----------------------------------------------------------

    def _train_dpo(self, rows: list[dict], output_dir: Path) -> Path:
        log.info("Starting DPO training  (beta=%.3f)", self.config.dpo_beta)
        synthetic_reward_gaps = [
            float(row["reward_gap"])
            for row in rows
            if row.get("source") == "synthetic" and row.get("reward_gap") is not None
        ]

        dataset = WhisperRLHFDataset(rows)
        if len(dataset) == 0:
            raise ValueError(
                "DPO dataset is empty -- no usable human or synthetic preferences."
            )

        model, processor = self._load_policy()
        ref = self._build_ref_model()
        ref.load()

        collator = WhisperRLHFCollator(processor, self.config)
        loader = DataLoader(
            dataset,
            batch_size=self.config.batch_size,
            shuffle=True,
            collate_fn=collator,
            drop_last=False,
            pin_memory=str(self.config.device).startswith("cuda"),
        )
        optimizer = torch.optim.AdamW(
            filter(lambda p: p.requires_grad, model.parameters()),
            lr=self.config.learning_rate,
            fused=use_fused_optimizer(self.config.device),
        )
        scaler = torch.cuda.amp.GradScaler(enabled=self.config.torch_dtype == "float16")
        beta = self.config.dpo_beta

        global_step = 0
        skipped_updates = 0
        batch_count = 0
        loss_sum = 0.0
        log_ratio_sum = 0.0
        gradient_norm_sum = 0.0
        planned_updates = (
            math.ceil(len(loader) / self.config.gradient_accumulation_steps)
            * self.config.num_epochs
        )
        completed_epochs = 0
        early_stopped = False
        early_stopping = EarlyStopping(self.config.early_stopping_patience)
        for epoch in tqdm(
            range(self.config.num_epochs), desc="DPO epochs", unit="epoch"
        ):
            optimizer.zero_grad()
            epoch_loss_sum = 0.0
            epoch_batch_count = 0

            for step, batch in enumerate(
                tqdm(loader, desc=f"  epoch {epoch+1}", unit="batch", leave=False)
            ):
                feats = batch["input_features"].to(
                    self.config.device, non_blocking=True
                )
                ch_labels = batch["chosen_labels"].to(
                    self.config.device, non_blocking=True
                )
                re_labels = batch["rejected_labels"].to(
                    self.config.device, non_blocking=True
                )

                with torch.cuda.amp.autocast(
                    enabled=self.config.torch_dtype == "float16"
                ):
                    # Policy log-probs (sum over sequence).
                    # Call base_model.model directly to bypass PeftModelForSeq2SeqLM.forward()
                    # which double-passes input_ids in newer PEFT versions.
                    ch_out = model.base_model.model(
                        input_features=feats, labels=ch_labels
                    )
                    re_out = model.base_model.model(
                        input_features=feats, labels=re_labels
                    )
                    pi_ch = _compute_logps_from_logits(ch_out.logits, ch_labels)
                    pi_re = _compute_logps_from_logits(re_out.logits, re_labels)

                    # Reference log-probs (frozen, no grad)
                    ref_ch = ref.compute_logps(feats, ch_labels)
                    ref_re = ref.compute_logps(feats, re_labels)

                    if epoch == 0 and step == 0:
                        initial_offset = _initial_reference_offset(
                            pi_ch, pi_re, ref_ch, ref_re
                        )
                        if not math.isfinite(initial_offset) or initial_offset > _MAX_INITIAL_REFERENCE_OFFSET:
                            ref.unload()
                            raise RuntimeError(
                                "DPO round-start policy/reference mismatch: "
                                f"mean absolute preference offset={initial_offset:.4f} "
                                f"(limit={_MAX_INITIAL_REFERENCE_OFFSET:.4f})"
                            )
                        log.info(
                            "DPO initial policy/reference offset=%.6f",
                            initial_offset,
                        )

                    # DPO loss
                    log_ratio = beta * ((pi_ch - ref_ch) - (pi_re - ref_re))
                    dpo_loss = -F.logsigmoid(log_ratio).mean()
                    loss = dpo_loss / self.config.gradient_accumulation_steps

                if not torch.isfinite(loss).item():
                    ref.unload()
                    raise RuntimeError("DPO loss is non-finite; refusing optimizer update")
                scaler.scale(loss).backward()
                batch_count += 1
                loss_sum += dpo_loss.item()
                log_ratio_sum += log_ratio.mean().item()
                epoch_loss_sum += dpo_loss.item()
                epoch_batch_count += 1

                is_accumulation_boundary = (
                    step + 1
                ) % self.config.gradient_accumulation_steps == 0
                is_epoch_tail = step + 1 == len(loader)
                if is_accumulation_boundary or is_epoch_tail:
                    gradient_norm = _scaled_optimizer_step(
                        model, optimizer, scaler, self.config.max_grad_norm
                    )
                    if gradient_norm is None:
                        skipped_updates += 1
                        continue
                    gradient_norm_sum += gradient_norm
                    global_step += 1

                    if global_step % self.config.logging_steps == 0:
                        log.info(
                            "epoch=%d  step=%d  dpo_loss=%.4f  log_ratio=%.4f",
                            epoch + 1,
                            global_step,
                            dpo_loss.item(),
                            log_ratio.mean().item(),
                        )

            completed_epochs = epoch + 1
            epoch_loss = epoch_loss_sum / epoch_batch_count
            if early_stopping.update(epoch_loss):
                early_stopped = True
                log.info(
                    "DPO early stopping after epoch %d (loss=%.4f patience=%d)",
                    completed_epochs,
                    epoch_loss,
                    self.config.early_stopping_patience,
                )
                break

        if global_step == 0:
            ref.unload()
            raise ValueError("DPO completed without an optimizer step")

        log.info(
            "DPO complete: epochs=%d batches=%d optimizer_updates=%d "
            "mean_loss=%.4f mean_log_ratio=%.4f",
            self.config.num_epochs,
            batch_count,
            global_step,
            loss_sum / batch_count,
            log_ratio_sum / batch_count,
        )
        self.store.set_setting(
            "training_dpo_diagnostics",
            json.dumps(
                {
                    "human_pairs": self.n_human_pairs,
                    "synthetic_pairs": self.n_synthetic_pairs,
                    "planned_optimizer_updates": planned_updates,
                    "optimizer_updates": global_step,
                    "skipped_optimizer_updates": skipped_updates,
                    "completed_epochs": completed_epochs,
                    "mean_loss": loss_sum / batch_count,
                    "mean_log_ratio": log_ratio_sum / batch_count,
                    "mean_gradient_norm": gradient_norm_sum / global_step,
                    "mean_synthetic_reward_margin": (
                        sum(synthetic_reward_gaps) / len(synthetic_reward_gaps)
                        if synthetic_reward_gaps
                        else None
                    ),
                    "early_stopped": early_stopped,
                }
            ),
        )
        ref.unload()
        return self._save_checkpoint(model, output_dir)

    # -- Checkpoint saving ------------------------------------------------------

    def _save_checkpoint(self, model, output_dir: Path) -> Path:
        from datetime import datetime

        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        ckpt = output_dir / f"whisper_{self.config.algorithm}_{ts}"
        model.save_pretrained(str(ckpt))
        self.config.to_json(ckpt / "rlhf_config.json")
        log.info("Checkpoint saved: %s", ckpt)
        return ckpt


# -- Per-sample log-probability helper -----------------------------------------


def _compute_logps_from_logits(
    logits: torch.Tensor,
    labels: torch.Tensor,
) -> torch.Tensor:
    """
    Compute per-sample sum of log-probabilities from teacher-forced logits.

    Args:
        logits: (B, T, V) -- output of model forward pass.
        labels: (B, T)    -- token IDs; -100 = padding (ignored).

    Returns:
        (B,) summed log-probs (higher = more likely).
    """
    shift_logits = logits[:, :-1, :].contiguous()  # (B, T-1, V)
    shift_labels = labels[:, 1:].contiguous()  # (B, T-1)

    log_probs = F.log_softmax(shift_logits, dim=-1)
    gathered = log_probs.gather(2, shift_labels.clamp(min=0).unsqueeze(2)).squeeze(
        2
    )  # (B, T-1)

    mask = (shift_labels != -100).float()
    return (gathered * mask).sum(dim=1)  # (B,)
